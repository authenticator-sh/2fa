export function getTranslation(language: Language, key: keyof TranslationKeys, ...args: (string | number)[]): string {
  let text = translations[language]?.[key] || translations.en[key] || key;
  args.forEach((arg, i) => {
    text = text.replace(`{${i}}`, String(arg));
  });
  return text;
}

export function createT(language: Language) {
  return (key: keyof TranslationKeys, ...args: (string | number)[]): string => getTranslation(language, key, ...args);
}
